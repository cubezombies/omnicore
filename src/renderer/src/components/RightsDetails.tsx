import { useState } from 'react';
import type { AudioTrack } from '../../../shared/production';
import { orMissing, RIGHTS_STATUS, trackSummary, type TrackRightsDetails } from '../../../shared/rights';
import { errorText } from './ProductionDetail';

/** Ask the app to open the Rights & Compliance page at one history entry. */
export function openRightsHistory(key?: string): void {
  window.dispatchEvent(new CustomEvent('omnicore:navigate', { detail: { page: 'rights', anchor: key } }));
}

/** The one status badge used everywhere (text + colour + title; never colour alone). */
export function RightsBadge({ status }: { status: AudioTrack['rightsStatus'] }) {
  const s = RIGHTS_STATUS[status];
  return (
    <span className={`badge rights-badge rights-${status}`} title={s.meaning} aria-label={`Rights: ${s.label}. ${s.meaning}`}>
      {s.label}
    </span>
  );
}

/** Concise rights summary for ordinary track views: status, creator, commercial use, attribution when required. */
export function RightsSummary({ t }: { t: AudioTrack }) {
  const s = trackSummary(t);
  return (
    <div className="rights-summary small">
      <div>
        <RightsBadge status={s.status} /> <span className={s.status === 'approved' ? 'muted' : 'field-error'}>{s.statusLine}</span>
      </div>
      <div className="muted">
        {s.creator} · <span className={s.commercial.eligible ? '' : 'field-error'}>{s.commercial.label}</span>
        {s.licence ? ` · ${s.licence}` : ''}
      </div>
      {s.attribution && <div className="muted">{s.attribution}</div>}
    </div>
  );
}

const when = (iso: string | null | undefined) => (iso ? new Date(iso).toLocaleString(undefined, { dateStyle: 'medium', timeStyle: 'short' }) : null);
const short = (h: string | null) => (h ? `${h.slice(0, 16)}…` : null);

/** Expandable full evidence for one sound. Loaded on demand; every missing item is stated as missing. */
export function RightsDetailsPanel({ t }: { t: AudioTrack }) {
  const [d, setD] = useState<TrackRightsDetails | null>(null);
  const [error, setError] = useState<string | null>(null);
  const load = () => {
    if (d || error) return;
    void window.api.soundRightsDetails(t.id).then(setD).catch((e: unknown) => setError(errorText(e)));
  };
  return (
    <details className="rights-details" onToggle={(e) => (e.currentTarget as HTMLDetailsElement).open && load()}>
      <summary>Rights &amp; Licensing details</summary>
      {error && <p className="field-error small" role="alert">{error}</p>}
      {!d && !error && <p className="muted small">Loading the rights record…</p>}
      {d && (
        <div className="small">
          {d.knownPaid && (
            <p className="field-error">
              <strong>Known paid track:</strong> {d.knownPaid}.
            </p>
          )}
          <dl className="pub-facts">
            <dt>Rights status</dt>
            <dd>
              <RightsBadge status={d.summary.status} /> {d.summary.statusLine}
            </dd>
            {d.reason && (
              <>
                <dt>Reason</dt>
                <dd>{d.reason}</dd>
              </>
            )}
            <dt>Verification</dt>
            <dd className={d.verification.establishesLicence ? '' : 'field-error'}>{d.verification.label}</dd>
            <dt>Origin</dt>
            <dd>{d.source.origin === 'generated' ? 'Generated by Omnicore' : `Imported via ${orMissing(d.source.provider, 'provider')}`}</dd>
            <dt>Source of record</dt>
            <dd>{d.source.sourceOfRecordUrl ? <a href={d.source.sourceOfRecordUrl} target="_blank" rel="noreferrer">{d.source.sourceOfRecordUrl}</a> : d.source.origin === 'generated' ? 'Not applicable (generated)' : orMissing(null, 'source-of-record page')}</dd>
            {d.source.origin !== 'generated' && (
              <>
                <dt>Asset identifier</dt>
                <dd className="mono">{orMissing(d.source.assetId, 'asset identifier')}{d.source.sourceName ? ` (${d.source.provider} record of a ${d.source.sourceName} track)` : ''}</dd>
              </>
            )}
            <dt>{d.recordedLicence.historical ? 'Licence claimed at import (historical)' : 'Licence'}</dt>
            <dd>
              {orMissing(d.recordedLicence.value, 'licence')}
              {d.recordedLicence.historical && d.recordedLicence.value ? ` · not verified at the source of record; not a current permission${d.recordedLicence.recordedAt ? ` · recorded ${when(d.recordedLicence.recordedAt)}` : ''}` : ''}
              {d.source.licenceUrl ? (
                <>
                  {' '}
                  · <a href={d.source.licenceUrl} target="_blank" rel="noreferrer">licence text</a>
                </>
              ) : null}
            </dd>
            <dt>Commercial use</dt>
            <dd>{d.summary.commercial.label} ({d.commercialUse})</dd>
            <dt>Attribution</dt>
            <dd>{d.attributionRequired === null ? orMissing(null, 'attribution requirement') : d.attributionRequired ? `Required${d.attributionText ? `: ${d.attributionText}` : ''}${d.recordedLicence.historical ? ' (as claimed at import)' : ''}` : 'Not required'}</dd>
            <dt>Download</dt>
            <dd>{d.source.origin === 'generated' ? 'Not applicable (generated)' : orMissing(d.permissions.download, 'download permission from the source of record')}</dd>
            <dt>Modification</dt>
            <dd>{d.source.origin === 'generated' ? 'Not applicable (generated)' : orMissing(d.permissions.modification, 'modification permission from the source of record')}</dd>
            <dt>File</dt>
            <dd className="mono">
              {d.file.name} · {d.file.present ? `SHA-256 ${short(d.file.sha256)}` : 'file missing'} ·{' '}
              {d.file.recordedSha256 ? (d.file.identityVerified ? 'matches the hash recorded at import' : 'DOES NOT match the hash recorded at import') : d.source.origin === 'generated' ? 'generated locally' : 'Missing: no file hash was recorded at import, so the file cannot be matched to the source'}
            </dd>
            {d.source.origin !== 'generated' && (
              <>
                <dt>Evidence record</dt>
                <dd className="mono">
                  {d.evidence.file} · {d.evidence.present ? `SHA-256 ${short(d.evidence.sha256)}` : 'Missing: evidence file not found'}
                  {d.evidence.matchesRecord === null ? '' : d.evidence.matchesRecord ? ' · matches the ledger' : ' · DOES NOT match the ledger'}
                </dd>
              </>
            )}
          </dl>
          <h5>Rights decisions (append-only)</h5>
          {d.decisions.length === 0 ? (
            <p className="field-error">Missing: no rights decision is recorded for this sound.</p>
          ) : (
            <ul className="rights-decisions">
              {d.decisions.map((x) => (
                <li key={x.id}>
                  <strong>{x.decision}</strong> · {when(x.decidedAt)} · verifier <span className="mono">{x.verifier}</span>
                  {x.reasons.length ? ` · ${x.reasons.join(' ')}` : ''}
                </li>
              ))}
            </ul>
          )}
          {(d.incidents.length > 0 || d.decisions.some((x) => x.verifier.startsWith('incident-'))) && (
            <p>
              Incident:{' '}
              {d.incidents.length ? d.incidents.map((i) => `#${i.id} (${i.status})`).join(', ') : 'referenced by the decision log'} ·{' '}
              <button className="link" onClick={() => openRightsHistory(d.incidents[0]?.historyKey ?? d.decisions.find((x) => x.verifier.startsWith('incident-'))?.verifier)}>
                Open in Rights &amp; Compliance history
              </button>
            </p>
          )}
          {d.missing.length > 0 && (
            <>
              <h5>Missing evidence</h5>
              <ul className="field-error">
                {d.missing.map((m) => (
                  <li key={m}>{m}</li>
                ))}
              </ul>
            </>
          )}
        </div>
      )}
    </details>
  );
}
