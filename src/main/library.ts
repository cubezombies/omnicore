/** I–vi–IV–V in C (root, third, fifth, octave; Hz). */
const CHORDS = [
  [261.63, 329.63, 392.0, 523.25],
  [220.0, 261.63, 329.63, 440.0],
  [174.61, 220.0, 261.63, 349.23],
  [196.0, 246.94, 293.66, 392.0]
];
/** Expression choosing CHORDS[c][k] from expressions c and k (frequency multiplied by mul). */
const pick = (c: string, k: string, mul = 1): string =>
  CHORDS.reduceRight((acc, ch, ci) => `if(eq(${c},${ci}),${ch.reduceRight((a, f, ki) => `if(eq(${k},${ki}),${(f * mul).toFixed(2)},${a})`, '0')},${acc})`, '0');
/** Seamless loop length (s): a whole number of chord cycles, so -stream_loop never hits a seam or fade. */
export const GENERATED_BED_SEC = 128;
/** Calm: 75 BPM; a plucked arpeggio (eighths) over a swelling chord pad and a soft bass with audible harmonics. */
function softKeysSource(): string {
  const bar = 3.2; // one chord per 4 beats at 75 BPM
  const c = `floor(mod(t,${bar * 4})/${bar})`;
  const step = 0.4; // eighth notes
  const k = `mod(floor(t/${step}),4)`;
  const m = `mod(t,${step})`;
  const f = pick(c, k, 2);
  const arp = `0.16*(sin(2*PI*${f}*t)+0.35*sin(4*PI*${f}*t)+0.12*sin(6*PI*${f}*t))*exp(-3.5*${m})*(1-exp(-300*${m}))*(1-exp(-200*(${step}-${m})))`;
  // Full level through each chord, with 150 ms fades only at the chord change (no click, no dip in the bed).
  const swell = `min(1,min(mod(t,${bar})/0.15,(${bar}-mod(t,${bar}))/0.15))`;
  const pad = `0.06*${swell}*(sin(2*PI*${pick(c, '0')}*t)+sin(2*PI*${pick(c, '1')}*t)+0.8*sin(2*PI*${pick(c, '2')}*t))`;
  const bass = `0.08*${swell}*(sin(PI*${pick(c, '0')}*t)+0.6*sin(2*PI*${pick(c, '0')}*t)+0.3*sin(3*PI*${pick(c, '0')}*t))`;
  return `aevalsrc=exprs='${arp}+${pad}+${bass}':s=48000:d=${GENERATED_BED_SEC}`;
}
/** Upbeat: 120 BPM; kick with a click, off-beat hats, a sixteenth-note arpeggio and an eighth-note bass line. */
function brightPulseSource(): string {
  const bar = 2; // one chord per bar at 120 BPM
  const c = `floor(mod(t,${bar * 4})/${bar})`;
  const kb = `mod(t,0.5)`;
  const kick = `0.35*sin(2*PI*(55+110*exp(-28*${kb}))*${kb})*exp(-9*${kb})+0.06*(random(0)*2-1)*exp(-250*${kb})`;
  const hat = `0.05*(random(1)*2-1)*exp(-70*mod(t+0.25,0.5))`;
  const m = `mod(t,0.125)`;
  const f = pick(c, `mod(floor(t/0.125),4)`, 2);
  const arp = `0.11*(sin(2*PI*${f}*t)+0.5*sin(4*PI*${f}*t)+0.2*sin(6*PI*${f}*t))*exp(-16*${m})*(1-exp(-400*${m}))*(1-exp(-300*(0.125-${m})))`;
  const bm = `mod(t,0.25)`;
  const r = pick(c, '0', 0.5);
  const bass = `0.14*(sin(2*PI*${r}*t)+0.6*sin(4*PI*${r}*t)+0.35*sin(6*PI*${r}*t)+0.2*sin(8*PI*${r}*t))*exp(-5*${bm})*(1-exp(-300*${bm}))*(1-exp(-200*(0.25-${bm})))`;
  return `aevalsrc=exprs='${kick}+${hat}+${arp}+${bass}':s=48000:d=${GENERATED_BED_SEC}`;
}

