import fs from 'node:fs';
import path from 'node:path';
import type { DatabaseSync } from 'node:sqlite';
import {
  SOUND_GENERATORS,
  type AudioKind,
  type AudioTrack,
  type AudioTrackPatch,
  type ProviderSettings,
  type SoundGeneratorId
} from '../shared/production';
import { NotFoundError } from './db/repository';
import { probe, runFfmpeg } from './media/ffmpeg';
import crypto from 'node:crypto';
import type { MusicOverride, SoundProfile } from '../shared/production';
import { MOOD_TAGS, allowedFor, clearedLicence, type Mood } from './audio/sound';
import { discoverMusicFor, licenceName, type DiscoveredAudio } from './audio/discovery';
import { downloadTo } from './providers/http';

interface Row {
  id: number;
  kind: AudioKind;
  title: string;
  file: string;
  duration_sec: number;
  license: string;
  attribution: string;
  source_url: string;
  tags: string;
  origin: AudioTrack['origin'];
  created_at: string;
  usage?: AudioTrack['usage'];
  commercial_use?: AudioTrack['commercialUse'];
  restrictions?: string;
  rights?: string;
}
const toTrack = (r: Row): AudioTrack => ({
  id: Number(r.id),
  kind: r.kind,
  title: r.title,
  file: r.file,
  durationSec: Number(r.duration_sec),
  license: r.license,
  attribution: r.attribution,
  sourceUrl: r.source_url,
  tags: JSON.parse(r.tags) as string[],
  origin: r.origin,
  createdAt: r.created_at,
  usage: r.usage ?? 'embedded',
  commercialUse: r.commercial_use ?? (r.origin === 'generated' ? 'yes' : 'unknown'),
  restrictions: r.restrictions ? (JSON.parse(r.restrictions) as AudioTrack['restrictions']) : {},
  rights: r.rights ? (JSON.parse(r.rights) as AudioTrack['rights']) : {}
});

export const GENERATED_LICENSE = 'Generated by Omnicore (no third-party rights)';

/** FFmpeg lavfi recipes for the built-in sounds: synthesised from maths, no samples involved. */
