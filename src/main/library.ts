/** Embedded use in a commercial video needs an embeddable track with confirmed commercial rights. */
export const embeddable = (t: AudioTrack): boolean => t.usage === 'embedded' && t.commercialUse === 'yes';

const AUDIO_EXT = /\.(mp3|wav|m4a|aac|ogg|flac|opus)$/i;

export class SoundLibrary {
  constructor(
    private readonly db: DatabaseSync,
    readonly dir: string,
    private readonly ffmpeg: () => string,
    /** Speech recognition used to refuse music with singing (it would compete with the narration). */
    private readonly transcribe?: (wav: string, signal?: AbortSignal) => Promise<string>
  ) {}

  /** Words a recogniser hears in two slices of a track; music tags like "[Music]" are ignored. */
  async heardWords(file: string, durationSec: number, signal?: AbortSignal): Promise<string> {
    if (!this.transcribe) return '';
    const out: string[] = [];
    for (const at of [Math.min(30, durationSec * 0.2), Math.min(90, durationSec * 0.55)]) {
      const clip = `${file}.vox.wav`;
      try {
        await runFfmpeg(this.ffmpeg(), ['-y', '-ss', at.toFixed(1), '-t', '25', '-i', file, '-ac', '1', '-ar', '16000', clip], { signal });
        out.push((await this.transcribe(clip, signal)).replace(/\[[^\]]*\]|\([^)]*\)|[♪*]/g, ' ').trim());
      } finally {
        fs.rmSync(clip, { force: true });
      }
    }
    return out.join(' ').replace(/\s+/g, ' ').trim();
  }

  list(kind?: AudioKind): AudioTrack[] {
    const rows = (kind
      ? this.db.prepare('SELECT * FROM audio_library WHERE kind = ? ORDER BY id').all(kind)
      : this.db.prepare('SELECT * FROM audio_library ORDER BY kind, id').all()) as unknown as Row[];
    return rows.map(toTrack);
  }

  get(id: number): AudioTrack {
    const r = this.db.prepare('SELECT * FROM audio_library WHERE id = ?').get(id) as Row | undefined;
    if (!r) throw new NotFoundError(`Sound ${id} not found`);
    return toTrack(r);
  }

  pathOf(t: AudioTrack): string {
    return path.join(this.dir, t.file);
  }

  private insert(t: Omit<AudioTrack, 'id' | 'createdAt' | 'rights'> & { rights?: AudioTrack['rights'] }): AudioTrack {
    const res = this.db
      .prepare('INSERT INTO audio_library (kind, title, file, duration_sec, license, attribution, source_url, tags, origin, usage, commercial_use, restrictions, rights) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)')
      .run(t.kind, t.title, t.file, t.durationSec, t.license, t.attribution, t.sourceUrl, JSON.stringify(t.tags), t.origin, t.usage, t.commercialUse, JSON.stringify(t.restrictions), JSON.stringify(t.rights ?? {}));
    return this.get(Number(res.lastInsertRowid));
  }

  private uniqueName(base: string): string {
    fs.mkdirSync(this.dir, { recursive: true });
    const ext = path.extname(base);
    const stem = path.basename(base, ext).replace(/[^\w.-]+/g, '_').slice(0, 60) || 'sound';
    let name = `${stem}${ext}`;
    for (let i = 2; fs.existsSync(path.join(this.dir, name)); i++) name = `${stem}-${i}${ext}`;
    return name;
  }

  async generate(id: SoundGeneratorId, signal?: AbortSignal): Promise<AudioTrack> {
    const g = SOUND_GENERATORS.find((x) => x.id === id);
    if (!g) throw new Error(`Unknown sound generator: ${id}`);
    const recipe = GENERATOR_RECIPES[id];
    const file = this.uniqueName(`${id}.m4a`);
    const out = path.join(this.dir, file);
    await runFfmpeg(this.ffmpeg(), ['-f', 'lavfi', '-i', recipe.source, '-af', recipe.filters, '-c:a', 'aac', '-b:a', '192k', out], { signal });
    const info = await probe(this.ffmpeg(), out);
    return this.insert({
      kind: g.kind,
      title: g.title,
      file,
      durationSec: info.durationSec,
      license: GENERATED_LICENSE,
      attribution: '',
      sourceUrl: '',
      tags: [...g.tags],
      origin: 'generated',
      usage: 'embedded',
      commercialUse: 'yes',
      restrictions: {}
    });
  }

  /** Copy a user-supplied audio file into the library. Licence details are the user's to provide. */
  async import(src: string, kind: AudioKind, meta: AudioTrackPatch = {}): Promise<AudioTrack> {
    if (!path.isAbsolute(src) || !AUDIO_EXT.test(src)) throw new Error('Choose an audio file (mp3, wav, m4a, aac, ogg, flac, opus).');
    if (!fs.existsSync(src)) throw new Error(`File not found: ${src}`);
    const info = await probe(this.ffmpeg(), src);
    if (!info.audio) throw new Error('That file has no audio track.');
    const file = this.uniqueName(path.basename(src));
    fs.copyFileSync(src, path.join(this.dir, file));
    return this.insert({
      kind,
      title: meta.title?.trim() || path.basename(src, path.extname(src)),
      file,
      durationSec: info.durationSec,
      license: meta.license?.trim() ?? '',
      attribution: meta.attribution?.trim() ?? '',
      sourceUrl: meta.sourceUrl?.trim() ?? '',
      tags: meta.tags ?? (kind === 'sfx' ? ['transition'] : []),
      origin: 'imported',
      usage: 'embedded',
      // The user must confirm commercial rights for imported files; until then they are never auto-selected.
      commercialUse: meta.commercialUse ?? 'unknown',
      restrictions: {}
    });
  }

  update(id: number, p: AudioTrackPatch): AudioTrack {
    const t = this.get(id);
    this.db
      .prepare('UPDATE audio_library SET title = ?, license = ?, attribution = ?, source_url = ?, tags = ?, commercial_use = ? WHERE id = ?')
      .run(p.title ?? t.title, p.license ?? t.license, p.attribution ?? t.attribution, p.sourceUrl ?? t.sourceUrl, JSON.stringify(p.tags ?? t.tags), p.commercialUse ?? t.commercialUse, id);
    return this.get(id);
  }

  delete(id: number): void {
    const t = this.get(id);
    this.db.prepare('DELETE FROM audio_library WHERE id = ?').run(id);
    const f = this.pathOf(t);
    if (path.dirname(f) === path.resolve(this.dir)) fs.rmSync(f, { force: true });
  }

  /**
   * Import a discovered track after checking it: the licence must allow commercial use and syncing to video, the file
   * must download and play, and its length must match what the provider reported. The provider's record is kept as
   * evidence (library/evidence/<file>.json) and its hash stored in the rights ledger.
   */
  async importDiscovered(a: DiscoveredAudio, mood: string | null, signal?: AbortSignal, allowShareAlike = false): Promise<AudioTrack> {
    const lic = clearedLicence(a.license, allowShareAlike);
    if (!lic.ok) throw new Error(`"${a.title}" cannot be used: ${lic.reason}.`);
    const existing = this.list(a.kind).find((t) => t.rights.provider === a.provider && t.rights.providerTrackId === a.providerId);
    if (existing) return existing;
    const ext = /\.(mp3|ogg|wav|flac|m4a)(\?|$)/i.exec(a.fileUrl)?.[1] ?? 'mp3';
    const file = this.uniqueName(`${a.source}-${a.title}.${ext}`);
    const out = path.join(this.dir, file);
    await downloadTo(a.fileUrl, out, { signal, timeoutMs: 120_000 });
    try {
      const size = fs.statSync(out).size;
      if (size > 40 * 1024 * 1024) throw new Error('file is larger than 40 MB');
      const info = await probe(this.ffmpeg(), out);
      if (!info.audio) throw new Error('the download has no audio');
      if (a.durationSec > 0 && Math.abs(info.durationSec - a.durationSec) > Math.max(3, a.durationSec * 0.1)) throw new Error(`the file is ${Math.round(info.durationSec)} s but the provider lists ${Math.round(a.durationSec)} s`);
      if (a.kind === 'music') {
        const heard = await this.heardWords(out, info.durationSec, signal);
        if (heard.split(/\s+/).filter((w) => /\p{L}{2,}/u.test(w)).length >= 4) throw new Error(`it has vocals (heard: "${heard.slice(0, 60)}")`);
      }
      const evidenceDir = path.join(this.dir, 'evidence');
      fs.mkdirSync(evidenceDir, { recursive: true });
      const evidence = JSON.stringify({ importedAt: new Date().toISOString(), provider: a.provider, record: a.record }, null, 2);
      fs.writeFileSync(path.join(evidenceDir, `${file}.json`), evidence);
      return this.insert({
        kind: a.kind,
        title: a.title,
        file,
        durationSec: info.durationSec,
        license: licenceName(a),
        attribution: a.creator,
        sourceUrl: a.landingUrl,
        tags: [...new Set([...(mood ? [mood] : []), ...a.tags])],
        origin: 'imported',
        usage: 'embedded',
        commercialUse: 'yes',
        restrictions: a.attributionRequired ? { notes: 'Credit required: title, creator and licence in the video description.' } : {},
        rights: {
          provider: a.provider,
          providerTrackId: a.providerId,
          source: a.source,
          licenseUrl: a.licenseUrl,
          landingUrl: a.landingUrl,
          attributionRequired: a.attributionRequired,
          evidenceSha256: crypto.createHash('sha256').update(evidence).digest('hex'),
          verifiedAt: new Date().toISOString()
        }
      });
    } catch (e) {
      fs.rmSync(out, { force: true });
      throw new Error(`"${a.title}" was not imported: ${(e as Error).message}`);
    }
  }

  /**
   * Story-aware selection for one production. Music: an override if set, else a cleared track for the story's mood
   * (discovering one when the library has none and discovery is allowed), avoiding the business's most recent tracks;
   * generated beds are the verified last resort. Every track must be allowed on every destination platform.
   */
  async select(
    s: ProviderSettings,
    productionId: number,
    o: { mood: Mood; platforms: string[]; profile: SoundProfile; override?: MusicOverride | null; recentTrackIds?: number[]; signal?: AbortSignal }
  ): Promise<{ music: AudioTrack | null; transition: AudioTrack | null; intro: AudioTrack | null; outro: AudioTrack | null; discovered: AudioTrack[]; refused: string[] }> {
    const ok = (t: AudioTrack) => embeddable(t) && allowedFor(t, o.platforms).ok && fs.existsSync(this.pathOf(t));
    const discovered: AudioTrack[] = [];
    const refused: string[] = [];
    let music: AudioTrack | null = null;
    if (o.override?.mode === 'track' && o.override.trackId) {
      music = this.get(o.override.trackId);
      if (music.kind !== 'music') throw new Error(`"${music.title}" is a sound effect, not music.`);
      if (!embeddable(music)) throw new Error(`"${music.title}" is not cleared for embedded commercial use.`);
      const allowed = allowedFor(music, o.platforms);
      if (!allowed.ok) throw new Error(`"${music.title}" is not licensed for ${allowed.blocked.join(', ')}.`);
    } else if (o.override?.mode !== 'none' && o.profile.music !== 'off') {
      const fits = (t: AudioTrack) => t.tags.some((g) => MOOD_TAGS[o.mood].includes(g));
      let pool = this.list('music').filter(ok).filter(fits);
      if (!pool.length && o.profile.autoDiscover) {
        try {
          const r = await discoverMusicFor(o.mood, { signal: o.signal, allowShareAlike: s.allowShareAlike, limit: 3 });
          refused.push(...r.refused.slice(0, 5).map((x) => `${x.title}: ${x.reason}`));
          for (const a of r.found) {
            try {
              discovered.push(await this.importDiscovered(a, o.mood, o.signal, s.allowShareAlike));
              if (discovered.length >= 2) break;
            } catch (e) {
              refused.push((e as Error).message);
            }
          }
        } catch (e) {
          refused.push(`Discovery unavailable: ${(e as Error).message}`);
        }
        pool = this.list('music').filter(ok).filter(fits);
      }
      if (!pool.length) {
        // Verified last resort: an Omnicore-generated bed close to the mood.
        const gen = o.mood === 'upbeat' || o.mood === 'tense' ? 'pulse-bed' : 'ambient-pad';
        pool = this.list('music').filter(ok).filter((t) => t.origin === 'generated' && t.title.startsWith(gen === 'pulse-bed' ? 'Pulse' : 'Ambient'));
        if (!pool.length) pool = [await this.generate(gen, o.signal)];
      }
      const fresh = pool.filter((t) => !(o.recentTrackIds ?? []).includes(t.id));
      const choose = fresh.length ? fresh : pool;
      music = choose[productionId % choose.length];
    }
    const sfxOf = async (tag: string, gen: SoundGeneratorId) => this.list('sfx').filter(ok).find((t) => t.tags.includes(tag)) ?? (await this.generate(gen, o.signal));
    const transition = o.profile.transitions || s.sfxTransitions ? await sfxOf('transition', 'whoosh') : null;
    const intro = o.profile.introAccent ? await sfxOf('build', 'riser') : null;
    const outro = o.profile.outroAccent ? await sfxOf('accent', 'pop') : null;
    for (const t of [music, transition, intro, outro]) if (t && !fs.existsSync(this.pathOf(t))) throw new Error(`Sound file missing from the library: ${t.title}.`);
    return { music, transition, intro, outro, discovered, refused };
  }

  /**
   * Choose music/SFX for a production from settings. "auto" picks a music track
   * deterministically per production; if the library has none, a generated one is
   * created so the choice is always a real, licensed file.
   */
  async pick(s: ProviderSettings, productionId: number, signal?: AbortSignal, mood: 'calm' | 'upbeat' = 'calm'): Promise<{ music: AudioTrack | null; sfx: AudioTrack | null }> {
    let music: AudioTrack | null = null;
    if (s.musicMode === 'track') {
      music = this.get(s.musicTrackId);
      if (music.kind !== 'music') throw new Error(`"${music.title}" is a sound effect, not music. Choose a music track in Studio → Providers.`);
      if (!embeddable(music)) throw new Error(`"${music.title}" is not cleared for embedded commercial use (${music.usage}, commercial use: ${music.commercialUse}).`);
    } else if (s.musicMode === 'auto') {
      // Only tracks cleared for embedding in a commercial video; prefer the mood that fits the content.
      let tracks = this.list('music').filter(embeddable);
      if (!tracks.length) tracks = [await this.generate(mood === 'upbeat' ? 'pulse-bed' : 'ambient-pad', signal)];
      const fitting = tracks.filter((t) => t.tags.some((g) => MOOD_TAGS[mood as Mood].includes(g)));
      const pool = fitting.length ? fitting : tracks;
      music = pool[productionId % pool.length];
    }
    let sfx: AudioTrack | null = null;
    if (s.sfxTransitions) {
      sfx = this.list('sfx').filter(embeddable).find((t) => t.tags.includes('transition')) ?? (await this.generate('whoosh', signal));
    }
    for (const t of [music, sfx]) if (t && !fs.existsSync(this.pathOf(t))) throw new Error(`Sound file missing from the library: ${t.title}. Remove it or re-import it.`);
    return { music, sfx };
  }
}
