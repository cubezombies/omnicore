      "aevalsrc=exprs='0.10*sin(2*PI*130.81*t)*(0.7+0.3*sin(2*PI*0.05*t))+0.08*sin(2*PI*164.81*t)*(0.6+0.4*sin(2*PI*0.07*t+1))+0.08*sin(2*PI*196.00*t)*(0.6+0.4*sin(2*PI*0.09*t+2))+0.05*sin(2*PI*246.94*t)*(0.5+0.5*sin(2*PI*0.11*t+3))':s=48000:d=60",
