import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import type { DatabaseSync } from 'node:sqlite';
import { GENERATOR_RECIPES, SoundLibrary } from '../../src/main/library';
import { runFfmpeg } from '../../src/main/media/ffmpeg';
import { SOUND_GENERATORS, type SoundGeneratorId } from '../../src/shared/production';

const CACHE = path.join(os.tmpdir(), 'aimo-test-sounds-v2');
const NEEDED: SoundGeneratorId[] = ['soft-keys', 'bright-pulse', 'whoosh', 'riser', 'pop'];

/**
 * A sound library with the real generated soundtrack and effects. The files are synthesised once per machine (the
 * 128 s beds take ~20 s each) and copied into every test library as approved generated tracks.
 */
export async function testSoundLibrary(db: DatabaseSync, ffmpeg: string, dir: string): Promise<SoundLibrary> {
  fs.mkdirSync(CACHE, { recursive: true });
  for (const id of NEEDED) {
    const f = path.join(CACHE, `${id}.m4a`);
    if (fs.existsSync(f) && fs.statSync(f).size > 0) continue;
    const r = GENERATOR_RECIPES[id];
    const tmp = `${f}.${process.pid}.tmp.m4a`;
    await runFfmpeg(ffmpeg, ['-f', 'lavfi', '-i', r.source, '-af', r.filters, '-c:a', 'aac', '-b:a', '192k', tmp]);
    try {
      fs.renameSync(tmp, f);
    } catch {
      fs.rmSync(tmp, { force: true }); // another worker won the race
    }
  }
  const lib = new SoundLibrary(db, dir, () => ffmpeg);
  fs.mkdirSync(dir, { recursive: true });
  const insert = (lib as unknown as { insert: (t: Record<string, unknown>) => unknown }).insert.bind(lib);
  for (const id of NEEDED) {
    const g = SOUND_GENERATORS.find((x) => x.id === id)!;
    const file = `${id}.m4a`;
    fs.copyFileSync(path.join(CACHE, file), path.join(dir, file));
    insert({ kind: g.kind, title: g.title, file, durationSec: g.kind === 'music' ? 128 : 1, license: 'Generated by Omnicore (no third-party rights)', attribution: '', sourceUrl: '', tags: [...g.tags], origin: 'generated', usage: 'embedded', commercialUse: 'yes', restrictions: {} });
  }
  return lib;
}
